"""Stable error codes, exit codes, and structured exception definitions for sciTree."""

from __future__ import annotations

from typing import Any

from scitree import SCHEMA_VERSION

# Stable error code constants
ERR_ROOT_NOT_CONFIGURED = "ROOT_NOT_CONFIGURED"
ERR_PROJECT_NOT_FOUND = "PROJECT_NOT_FOUND"
ERR_PROJECT_ALREADY_EXISTS = "PROJECT_ALREADY_EXISTS"
ERR_VERSION_NOT_FOUND = "VERSION_NOT_FOUND"
ERR_VERSION_CONFLICT = "VERSION_CONFLICT"
ERR_VERSION_IMMUTABLE = "VERSION_IMMUTABLE"
ERR_COMMENT_NOT_FOUND = "COMMENT_NOT_FOUND"
ERR_TEMPLATE_NOT_FOUND = "TEMPLATE_NOT_FOUND"
ERR_RISK_NOT_FOUND = "RISK_NOT_FOUND"
ERR_MILESTONE_NOT_FOUND = "MILESTONE_NOT_FOUND"
ERR_ZOTERO_UNAVAILABLE = "ZOTERO_UNAVAILABLE"
ERR_EXPORT_FAILED = "EXPORT_FAILED"
ERR_ACTOR_REQUIRED = "ACTOR_REQUIRED"
ERR_VALIDATION_ERROR = "VALIDATION_ERROR"
ERR_FILE_NOT_FOUND = "FILE_NOT_FOUND"
ERR_UNAUTHORIZED = "UNAUTHORIZED"
ERR_INTERNAL_ERROR = "INTERNAL_ERROR"

# Documented CLI exit codes
EXIT_OK = 0
EXIT_VALIDATION_ERROR = 2
EXIT_ROOT_NOT_CONFIGURED = 3
EXIT_NOT_FOUND = 4
EXIT_CONFLICT_OR_IMMUTABLE = 5
EXIT_ACTOR_REQUIRED = 6
EXIT_EXTERNAL_OR_EXPORT = 7
EXIT_UNAUTHORIZED = 8
EXIT_INTERNAL = 1

ERROR_EXIT_CODE_MAP: dict[str, int] = {
    ERR_VALIDATION_ERROR: EXIT_VALIDATION_ERROR,
    ERR_FILE_NOT_FOUND: EXIT_VALIDATION_ERROR,
    ERR_ROOT_NOT_CONFIGURED: EXIT_ROOT_NOT_CONFIGURED,
    ERR_PROJECT_NOT_FOUND: EXIT_NOT_FOUND,
    ERR_VERSION_NOT_FOUND: EXIT_NOT_FOUND,
    ERR_COMMENT_NOT_FOUND: EXIT_NOT_FOUND,
    ERR_TEMPLATE_NOT_FOUND: EXIT_NOT_FOUND,
    ERR_RISK_NOT_FOUND: EXIT_NOT_FOUND,
    ERR_MILESTONE_NOT_FOUND: EXIT_NOT_FOUND,
    ERR_PROJECT_ALREADY_EXISTS: EXIT_CONFLICT_OR_IMMUTABLE,
    ERR_VERSION_CONFLICT: EXIT_CONFLICT_OR_IMMUTABLE,
    ERR_VERSION_IMMUTABLE: EXIT_CONFLICT_OR_IMMUTABLE,
    ERR_ACTOR_REQUIRED: EXIT_ACTOR_REQUIRED,
    ERR_ZOTERO_UNAVAILABLE: EXIT_EXTERNAL_OR_EXPORT,
    ERR_EXPORT_FAILED: EXIT_EXTERNAL_OR_EXPORT,
    ERR_UNAUTHORIZED: EXIT_UNAUTHORIZED,
    ERR_INTERNAL_ERROR: EXIT_INTERNAL,
}

ERROR_HTTP_STATUS_MAP: dict[str, int] = {
    ERR_VALIDATION_ERROR: 400,
    ERR_FILE_NOT_FOUND: 400,
    ERR_ACTOR_REQUIRED: 400,
    ERR_UNAUTHORIZED: 401,
    ERR_PROJECT_NOT_FOUND: 404,
    ERR_VERSION_NOT_FOUND: 404,
    ERR_COMMENT_NOT_FOUND: 404,
    ERR_TEMPLATE_NOT_FOUND: 404,
    ERR_RISK_NOT_FOUND: 404,
    ERR_MILESTONE_NOT_FOUND: 404,
    ERR_PROJECT_ALREADY_EXISTS: 409,
    ERR_VERSION_CONFLICT: 409,
    ERR_VERSION_IMMUTABLE: 409,
    ERR_ROOT_NOT_CONFIGURED: 412,
    ERR_EXPORT_FAILED: 500,
    ERR_ZOTERO_UNAVAILABLE: 503,
    ERR_INTERNAL_ERROR: 500,
}


class SciTreeError(Exception):
    """Structured exception carrying a machine-readable error code and details."""

    def __init__(
        self,
        code: str,
        message: str,
        details: dict[str, Any] | None = None,
    ) -> None:
        super().__init__(message)
        self.code = code
        self.message = message
        self.details = details or {}

    @property
    def exit_code(self) -> int:
        return ERROR_EXIT_CODE_MAP.get(self.code, EXIT_INTERNAL)

    @property
    def http_status(self) -> int:
        return ERROR_HTTP_STATUS_MAP.get(self.code, 500)

    def to_dict(self) -> dict[str, Any]:
        return {
            "schema_version": SCHEMA_VERSION,
            "error": self.code,
            "message": self.message,
            "details": self.details,
        }
